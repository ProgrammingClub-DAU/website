-- What an event looks like once it is over: a contest link, and a podium.
--
-- Three separate visibility switches rather than one "results published" flag.
-- The club wants to announce these at different moments: the contest link is
-- often shared the moment the round opens, while winners cannot be known until
-- it closes, and the turnout figure is sometimes held back entirely. One flag
-- would force all three to the same schedule.
--
-- All three default to FALSE. A newly created event therefore shows the public
-- only what it always showed -- title, date, place, description, photos -- until
-- somebody decides otherwise. Defaulting to visible would publish the turnout of
-- every event that already exists the moment this migration ran.

ALTER TABLE events ADD COLUMN IF NOT EXISTS codeforces_contest_url VARCHAR(512);
ALTER TABLE events ADD COLUMN IF NOT EXISTS show_contest_link BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE events ADD COLUMN IF NOT EXISTS show_winners BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE events ADD COLUMN IF NOT EXISTS show_attendee_count BOOLEAN NOT NULL DEFAULT FALSE;

-- The podium. One row per placing, and a placing points at a member rather than
-- carrying a name: a winner is somebody with a profile on this site, so the
-- public page can link to it, and a member who corrects their name does not
-- leave a stale copy of it sitting in an old event.
CREATE TABLE IF NOT EXISTS event_winners (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    event_id BIGINT  NOT NULL,
    user_id  BIGINT  NOT NULL,

    -- 1, 2 or 3. Constrained in the database as well as in the application
    -- because it is the column the public page orders by, and a 0 or a 7 would
    -- render as a podium position that does not exist.
    position INTEGER NOT NULL,

    PRIMARY KEY (id),

    CONSTRAINT fk_event_winners_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT fk_event_winners_user  FOREIGN KEY (user_id)  REFERENCES users  (id) ON DELETE CASCADE,

    CONSTRAINT event_winners_position_check CHECK (position BETWEEN 1 AND 3),

    -- One member per placing, and one placing per member. Without these a
    -- mis-click could leave an event with two first places, or the same person
    -- standing first and third.
    CONSTRAINT event_winners_unique_position UNIQUE (event_id, position),
    CONSTRAINT event_winners_unique_member   UNIQUE (event_id, user_id)
);

-- The public event page reads the podium for one event at a time, in order.
CREATE INDEX IF NOT EXISTS idx_event_winners_event ON event_winners (event_id, position);
